const interpolate = (template, values) => template.replace(/\{(\d+)\}/g, (token, index) =>
  Number(index) < values.length ? String(values[Number(index)] ?? '') : token);
export function translate(language, source, ...values) {
  return interpolate(language === 'en' ? english[source] ?? source : source, values);
}

const reverse = Object.fromEntries(Object.entries(english).map(([source, translation]) => [translation, source]));
export function translateMessage(language, message) {
  if (typeof message !== 'string') return message;
  const dictionary = language === 'en' ? english : reverse;
  return Object.hasOwn(dictionary, message) ? dictionary[message] : message;
}
